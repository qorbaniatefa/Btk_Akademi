import { chromium } from '@playwright/test';
import fs from 'node:fs';
fs.mkdirSync('test-results',{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--enable-webgl','--use-angle=swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/?mode=tour');
await page.waitForFunction(()=>window.__havana?.ready,{timeout:60000});
await page.waitForTimeout(1000);
await page.screenshot({path:'test-results/desktop.png'});
console.log('scene',await page.evaluate(()=>({meshes:window.__havana.clickable.length,position:window.__havana.camera.position.toArray(),size:window.__havana.model.scale.toArray()})));
await page.evaluate(()=>scrollTo(0,(document.documentElement.scrollHeight-innerHeight)*.5));
await page.waitForTimeout(1500);
await page.screenshot({path:'test-results/detail.png'});
console.log('scroll',await page.evaluate(()=>({progress:window.__havana.progress,position:window.__havana.camera.position.toArray()})));
const benchPoint=await page.evaluate(()=>{
 const app=window.__havana;const bench=app.props.children.find(o=>o.name==='Ahşap sokak bankı');
 const point=bench.children[0].position.clone();bench.children[0].getWorldPosition(point);point.project(app.camera);
 return {x:(point.x+1)*innerWidth/2,y:(1-point.y)*innerHeight/2};
});
await page.mouse.click(benchPoint.x,benchPoint.y);
await page.waitForTimeout(1000);
if(!await page.evaluate(()=>window.__havana.free))throw Error('Object focus failed');
if(!await page.locator('.focus-panel').isVisible())throw Error('Focus panel missing');
console.log('focused',await page.locator('#focus-name').textContent());
if(await page.locator('#focus-name').textContent()!=='Ahşap sokak bankı')throw Error('Expected bench focus');
await page.locator('#return').click();
await page.locator('#mode').click();
if(!await page.evaluate(()=>window.__havana.free))throw Error('Free mode failed');
await page.locator('#zoom-in').click();
await page.locator('#mode').click();
await page.evaluate(()=>scrollTo(0,0));
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(1500);
await page.screenshot({path:'test-results/mobile.png'});
console.log('errors',errors);
await browser.close();
if(errors.length)process.exit(1);
